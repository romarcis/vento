const pick = () => {
  for (const l of navigator.languages ?? [navigator.language]) {
    const k = (l || "").slice(0, 2).toLowerCase();
    if (STRINGS[k]) return k;
  }
  return "en";
};
export const lang = pick();
const dict = STRINGS[lang];

/** Translated string for `key`, with {placeholders} filled from `vars`. */
export function t(key, vars = {}) {
  const s = dict[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

/** Fills every [data-i18n] element's text and every [data-i18n-<attr>] attribute. */
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const attr of ["title", "aria-label", "placeholder"]) {
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
  }
}
